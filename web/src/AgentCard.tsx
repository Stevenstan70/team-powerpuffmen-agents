import { useEffect, useRef, useState } from "react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { ApiError, runAgent, type AgentResult } from "./api";

type Phase =
  | { name: "idle" }
  | { name: "loading" }
  | { name: "error"; message: string }
  | { name: "done"; result: AgentResult };

export default function AgentCard({ researchId }: { researchId: string }) {
  const [phase, setPhase] = useState<Phase>({ name: "idle" });
  const [elapsed, setElapsed] = useState(0);
  const abort = useRef<AbortController | null>(null);

  useEffect(() => () => abort.current?.abort(), []);

  useEffect(() => {
    if (phase.name !== "loading") return;
    const start = performance.now();
    setElapsed(0);
    const id = setInterval(() => setElapsed((performance.now() - start) / 1000), 200);
    return () => clearInterval(id);
  }, [phase.name]);

  async function ask() {
    abort.current?.abort();
    const controller = new AbortController();
    abort.current = controller;
    setPhase({ name: "loading" });
    try {
      setPhase({ name: "done", result: await runAgent(researchId, controller.signal) });
    } catch (err) {
      if ((err as Error).name === "AbortError") return;
      setPhase({
        name: "error",
        message: err instanceof ApiError ? err.message : "Unexpected error: " + (err as Error).message,
      });
    }
  }

  return (
    <section className="card">
      <div className="eyebrow">IBM WATSONX ORCHESTRATE AGENT</div>
      <h2>Agent research summary</h2>
      <p className="fineprint">
        The agent plans its steps, calls two tools (the four-rule snapshot
        screen and the price-trend check) and explains what is verified,
        missing and conflicting. It does not retrieve data and does not
        recommend trades. Pressing the button sends the evidence summary
        listed below to your Orchestrate agent.
      </p>
      <button className="button primary" onClick={ask} disabled={phase.name === "loading"}>
        {phase.name === "loading" ? `Agent working… ${elapsed.toFixed(0)} s` : "Ask the IBM agent"}
      </button>

      {phase.name === "error" && (
        <div className="notice error" role="alert">
          <b>The agent could not complete this request</b>
          <p>{phase.message}</p>
          <p>Nothing was substituted.</p>
        </div>
      )}

      {phase.name === "done" && <AgentResultView r={phase.result} />}
    </section>
  );
}

function AgentResultView({ r }: { r: AgentResult }) {
  const m = r.tool_markers_in_response;
  return (
    <>
      <div className="notice warn">
        <b>AI-generated by the Orchestrate agent</b>
        <p>
          Not a verified fact. The application supplied the evidence; the agent
          retrieved nothing. Completed in {r.elapsed_seconds.toFixed(1)} s.
        </p>
      </div>
      <article className="brief">
        <ReactMarkdown remarkPlugins={[remarkGfm]}>{r.content}</ReactMarkdown>
      </article>
      <h3 className="sub">Evidence of tool use</h3>
      <ul className="plain-list">
        <li>Run id: {r.run_id ?? "not returned"}; trace id: {r.trace_id ?? "not returned"}</li>
        <li>Snapshot-screen version string in the reply: {m.snapshot_screen ? "yes" : "no"}</li>
        <li>Trend-check version string in the reply: {m.trend_check ? "yes" : "no"}</li>
      </ul>
      <p className="fineprint">
        The version-string check is weak. Open the run in the Orchestrate
        trace to confirm both tool calls before claiming tool orchestration.
      </p>
      <details className="provenance">
        <summary>Data sent to the agent</summary>
        <pre>{JSON.stringify(r.evidence_sent, null, 2)}</pre>
      </details>
    </>
  );
}
